#!/usr/bin/env python3
"""Generate curated Conda environment specifications for PGL."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]

# Application dependencies shared by analysis and graphics environments.
BASE = [
    "python=3.12",
    "numpy",
    "pandas",
    "scipy",
    "xarray",
    "pyarrow",
    "h5py",
    "fsspec",
    "paramiko",
    "psycopg>=3,<4",
    "keyring",
    "traitlets",
    "ipython",
    "ipywidgets",
    "ipykernel",
    "matplotlib",
    "pyside6",
    "pillow",
    "imageio",
    "tqdm",
]

# Tools for installing/developing PGL from this checkout.
TOOLS = [
    "pip",
    "setuptools>=77.0.3",
    "wheel",
]

# Shared pip dependencies, with platform-specific installation markers.
BASE_PIP = [
    "windows-curses; sys_platform == 'win32'",
]

MNE = [
    "mne",
]

MACOS = [
    "psutil",
    "pyserial",
    "pynput",
]

# Install the PyObjC bindings used by display discovery and settings saves.
MACOS_PIP = [
    "pyobjc-framework-Quartz; sys_platform == 'darwin'",
    "pyobjc-framework-Cocoa; sys_platform == 'darwin'",
    "pyobjc-framework-ColorSync; sys_platform == 'darwin'",
]

# MRI analysis, DICOM conversion, array storage, and remote filesystem access.
MRI = [
    "dcm2niix",
    "nibabel",
    "scikit-learn",
    "numba",
    "dask",
    "zarr>=2.18,<3",
    "numcodecs<0.16",
    "sshfs",
]

# Additional interfaces and integrations for the MRI environment.
MRI_INTEGRATIONS = [
    "gspread",
    "google-auth-oauthlib",
    "oauth2client",
    "gradio",
    "pysimplegui=4.60.5",
    "requests",
    "pyyaml",
]

# Preserve pip-installed MRI services and hardware bindings.
# GLMsingle is installed separately from its source checkout.
# labjack-ljm also requires the system LJM driver for hardware access.
MRI_PIP = [
    "flywheel-sdk",
    "fracridge",
    "labjack-ljm",
    "pypng",
]

ENVIRONMENTS = {
    "pgl": {
        "conda": [],
        "pip": [],
    },
    "pgl_mne": {
        "conda": MNE,
        "pip": [],
    },
    "pgl_mri": {
        "conda": MRI + MRI_INTEGRATIONS,
        "pip": MRI_PIP,
    },
}


# ========================================================================
# Render one environment with the requested platform dependencies
# ========================================================================
def renderEnvironment(name, *, macOS=False):
    dependencies = ENVIRONMENTS[name]
    condaPackages = BASE + TOOLS + (MACOS if macOS else []) + dependencies["conda"]
    pipPackages = BASE_PIP + (MACOS_PIP if macOS else []) + dependencies["pip"]
    if len(condaPackages) != len(set(condaPackages)):
        raise ValueError(f"Duplicate dependency specification in {name}")

    lines = [
        "# Generated by scripts/makeEnvironments.py; edit that script.",
        f"name: {json.dumps(name)}",
        "channels:",
        "  - conda-forge",
        "  - nodefaults",
        "dependencies:",
    ]

    lines.extend(f"  - {json.dumps(spec)}" for spec in condaPackages)

    if pipPackages:
        lines.append("  - pip:")
        lines.extend(f"      - {json.dumps(spec)}" for spec in pipPackages)

    return "\n".join(lines) + "\n"


# ========================================================================
# Write portable specs for direct Conda use
# ========================================================================
def main():
    for name in ENVIRONMENTS:
        path = ROOT / f"{name}.yml"
        contents = renderEnvironment(name)

        if path.exists() and path.read_text(encoding="utf-8") == contents:
            print(f"Unchanged: {path.name}")
            continue

        temporary = path.with_suffix(path.suffix + ".tmp")
        temporary.write_text(contents, encoding="utf-8")
        temporary.replace(path)
        print(f"Wrote: {path.name}")


if __name__ == "__main__":
    main()
