#!/usr/bin/env python3
"""Generate curated Conda environment specifications for PGL."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]

# Application dependencies shared by analysis and graphics environments.
BASE = [
    "python=3.12",
    "numpy",
    "pandas",
    "scipy",
    "xarray",
    "pyarrow",
    "fsspec",
    "paramiko",
    "psycopg>=3,<4",
    "keyring",
    "traitlets",
    "ipython",
    "ipywidgets",
    "ipykernel",
    "matplotlib",
    "pyside6",
    "pillow",
    "imageio",
    "tqdm",
]

# Tools for installing/developing PGL from this checkout.
TOOLS = [
    "pip",
    "setuptools>=77.0.3",
    "wheel",
]

# Shared pip dependencies, with platform-specific installation markers.
BASE_PIP = [
    "windows-curses; sys_platform == 'win32'",
]

MNE = [
    "mne",
]

MACOS = [
    "psutil",
    "pyserial",
    "pynput",
    "h5py",
]

# Install via pip after Conda packages. PyObjC provides the Apple
# framework bindings used by graphics settings.
MACOS_PIP = [
    "pyobjc; sys_platform == 'darwin'",
]

ENVIRONMENTS = {
    "pgl": {
        "conda": BASE + TOOLS,
        "pip": BASE_PIP,
    },
    "pgl_mne": {
        "conda": BASE + TOOLS + MNE,
        "pip": BASE_PIP,
    },
    "pgl_macos": {
        "conda": BASE + TOOLS + MACOS,
        "pip": BASE_PIP + MACOS_PIP,
    },
}

def render_environment(name, conda_packages, pip_packages):
    if len(conda_packages) != len(set(conda_packages)):
        raise ValueError(f"Duplicate dependency specification in {name}")

    lines = [
        "# Generated by scripts/makeEnvironments.py; edit that script.",
        f"name: {json.dumps(name)}",
        "channels:",
        "  - conda-forge",
        "  - nodefaults",
        "dependencies:",
    ]

    lines.extend(f"  - {json.dumps(spec)}" for spec in conda_packages)

    if pip_packages:
        lines.append("  - pip:")
        lines.extend(f"      - {json.dumps(spec)}" for spec in pip_packages)

    return "\n".join(lines) + "\n"


def main():
    for name, dependencies in ENVIRONMENTS.items():
        path = ROOT / f"{name}.yml"
        contents = render_environment(
            name,
            dependencies["conda"],
            dependencies["pip"],
        )

        if path.exists() and path.read_text(encoding="utf-8") == contents:
            print(f"Unchanged: {path.name}")
            continue

        temporary = path.with_suffix(path.suffix + ".tmp")
        temporary.write_text(contents, encoding="utf-8")
        temporary.replace(path)
        print(f"Wrote: {path.name}")


if __name__ == "__main__":
    main()